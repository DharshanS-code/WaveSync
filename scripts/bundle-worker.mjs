// Make the three dependency-free ES modules pasteable in Cloudflare's editor.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = [
  ['shared/protocol.js', []],
  ['backend/room-state.js', ['../shared/protocol.js']],
  ['backend/worker.js', ['./room-state.js', '../shared/protocol.js']]
];
let output = '// Generated by node scripts/bundle-worker.mjs. Paste the whole file into Cloudflare.\n';
for (const [file, imports] of modules) {
  let text = await readFile(resolve(root, file), 'utf8');
  for (const dependency of imports) {
    const statement = text.split('\n').find(line => line.startsWith('import ') && line.includes(`'${dependency}'`));
    if (!statement) throw new Error(`Unexpected module imports in ${file}; update bundler first.`);
    text = text.replace(statement, '');
  }
  if (/^\s*import\s/m.test(text)) throw new Error(`Unresolved import in ${file}`);
  if (file !== 'backend/worker.js') text = text.replace(/^export (?=(?:const|function|class)\b)/gm, '');
  output += `\n// ---- ${file} ----\n${text}\n`;
}
await writeFile(resolve(root, 'backend/dashboard-worker.js'), output);
const dashboard = resolve(root, '../cloudflare-dashboard');
await mkdir(dashboard, { recursive: true });
await writeFile(resolve(dashboard, 'worker.js'), output);
console.log('Created backend/dashboard-worker.js and WaveSync/cloudflare-dashboard/worker.js.');
